"""
OS-level egress enforcement (Linux) for code the in-process guard cannot see.

The audit-hook guard (``ulpf.runtime.egress``) sees connections made through
Python's ``socket`` module. Native libraries — librdkafka (confluent-kafka),
the AWS C++ SDK inside pyarrow, DuckDB extensions — call ``connect(2)``
directly and are invisible to it. Only the kernel can stop those, so this
module renders the ``airgap.allow`` policy for two kernel mechanisms and
checks that one is in force:

    ulpf airgap os-policy --format nftables -c pipeline.yaml --user ulpf | sudo nft -f -
    ulpf airgap os-policy --format systemd  -c pipeline.yaml > /etc/systemd/system/ulpf.service.d/egress.conf
    ulpf airgap os-check                    # exit 0 only if the kernel refuses a non-allowed connect()

* ``nftables``: an output-hook filter on packets owned by the service user
  (``meta skuid``). Outbound only: replies on connections other hosts open
  to ULPF's listeners pass (``ct state established``).
* ``systemd``: ``IPAddressDeny=any`` + ``IPAddressAllow=`` (cgroup BPF) on the
  unit. This filters **both directions**, so syslog/HTTP senders' networks
  must be listed too (``--ingress-from``).

Host names in ``airgap.allow`` are resolved when the policy is rendered;
re-render when their addresses change (or list CIDRs). If names are used, the
DNS resolvers must be reachable: list them (``--allow-dns`` adds the
nameservers in /etc/resolv.conf).
"""
from __future__ import annotations

import ipaddress
import os
import socket
import sys
import time


def resolve_allow(allow: list[str]) -> tuple[list[str], list[str], list[str]]:
    """``airgap.allow`` → (IPv4 CIDRs, IPv6 CIDRs, names that did not resolve)."""
    v4: set[str] = set()
    v6: set[str] = set()
    unresolved: list[str] = []
    for entry in allow or []:
        host = str(entry).strip()
        if not host:
            continue
        try:
            net = ipaddress.ip_network(host, strict=False)
            (v4 if net.version == 4 else v6).add(str(net))
            continue
        except ValueError:
            pass
        try:
            for info in socket.getaddrinfo(host, None):
                ip = ipaddress.ip_address(str(info[4][0]).split("%")[0])
                (v4 if ip.version == 4 else v6).add(f"{ip}/{ip.max_prefixlen}")
        except OSError:
            unresolved.append(host)
    return sorted(v4), sorted(v6), unresolved


def resolv_conf_nameservers(path: str = "/etc/resolv.conf") -> list[str]:
    out = []
    try:
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                parts = line.split()
                if len(parts) >= 2 and parts[0] == "nameserver":
                    out.append(parts[1])
    except OSError:
        pass
    return out


def _header(unresolved: list[str], fmt: str) -> list[str]:
    lines = [f"# Generated by `ulpf airgap os-policy --format {fmt}` at "
             f"{time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}.",
             "# Host names were resolved now: re-render when their addresses change."]
    for name in unresolved:
        lines.append(f"# WARNING: {name!r} did not resolve and is NOT allowed by this policy")
    return lines


def render_nftables(allow: list[str], user: str = "ulpf", allow_dns: bool = False) -> str:
    entries = list(allow or []) + (resolv_conf_nameservers() if allow_dns else [])
    v4, v6, unresolved = resolve_allow(entries)
    v4 = ["127.0.0.0/8"] + [n for n in v4 if n != "127.0.0.0/8"]
    v6 = ["::1/128"] + [n for n in v6 if n != "::1/128"]
    lines = _header(unresolved, "nftables") + [
        "add table inet ulpf_egress",          # create-then-delete: re-applying replaces the old rules
        "delete table inet ulpf_egress",
        "table inet ulpf_egress {",
        "  set allow4 {", "    type ipv4_addr; flags interval;",
        f"    elements = {{ {', '.join(v4)} }}", "  }",
        "  set allow6 {", "    type ipv6_addr; flags interval;",
        f"    elements = {{ {', '.join(v6)} }}", "  }",
        "  chain output {",
        "    type filter hook output priority 0; policy accept;",
        f'    meta skuid != "{user}" accept',
        "    ct state established,related accept",
        '    oifname "lo" accept',
        "    ip daddr @allow4 accept",
        "    ip6 daddr @allow6 accept",
        '    counter log prefix "ulpf-egress-drop " level warn drop',
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def render_systemd(allow: list[str], ingress_from: list[str] | None = None, allow_dns: bool = False) -> str:
    entries = list(allow or []) + list(ingress_from or []) + (resolv_conf_nameservers() if allow_dns else [])
    v4, v6, unresolved = resolve_allow(entries)
    lines = _header(unresolved, "systemd") + [
        "# IPAddressDeny/IPAddressAllow filter BOTH directions: every network that sends",
        "# logs to this node must be allowed as well (--ingress-from).",
        "[Service]",
        "IPAddressDeny=any",
        "IPAddressAllow=localhost",
    ]
    lines += [f"IPAddressAllow={n}" for n in v4 + v6]
    lines += ["RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK"]
    return "\n".join(lines) + "\n"


def os_check(target: tuple[str, int] = ("192.0.2.1", 9), timeout: float = 2.0) -> dict:
    """Ask the kernel to connect to a non-allowed address, bypassing Python's socket module.

    The connect goes through libc directly (as librdkafka's would), so the
    audit-hook guard does not see it. ``blocked`` is True when the kernel
    refuses it (EPERM/EACCES: an nftables drop or a cgroup BPF filter).
    The default target is TEST-NET-1 (RFC 5737): nothing answers there.
    """
    if not sys.platform.startswith("linux"):
        return {"supported": False, "blocked": None,
                "detail": "OS-level egress enforcement is only implemented for Linux"}
    import ctypes
    import errno
    import select
    import struct

    libc = ctypes.CDLL(None, use_errno=True)
    host, port = target
    fd = libc.socket(socket.AF_INET, socket.SOCK_STREAM | getattr(socket, "SOCK_NONBLOCK", 0o4000), 0)
    if fd < 0:
        return {"supported": True, "blocked": None, "detail": os.strerror(ctypes.get_errno())}
    try:
        # struct sockaddr_in: sin_family (host order), sin_port (network order), sin_addr, 8 zero bytes
        addr = struct.pack("=H", socket.AF_INET) + struct.pack("!H", port) + socket.inet_aton(host) + bytes(8)
        buf = ctypes.create_string_buffer(addr, len(addr))
        rc = libc.connect(fd, buf, len(addr))
        err = 0 if rc == 0 else ctypes.get_errno()
        if err in (errno.EPERM, errno.EACCES):
            return {"supported": True, "blocked": True, "target": f"{host}:{port}",
                    "detail": f"kernel refused connect(): {errno.errorcode[err]}"}
        if err == errno.EINPROGRESS:
            # The SYN left the host (no kernel filter); give a late EPERM a moment to show up
            select.select([], [fd], [], min(timeout, 0.5))
            so_err = ctypes.c_int(0)
            ln = ctypes.c_uint(ctypes.sizeof(so_err))
            libc.getsockopt(fd, socket.SOL_SOCKET, socket.SO_ERROR, ctypes.byref(so_err), ctypes.byref(ln))
            if so_err.value in (errno.EPERM, errno.EACCES):
                return {"supported": True, "blocked": True, "target": f"{host}:{port}",
                        "detail": f"kernel refused connect(): {errno.errorcode[so_err.value]}"}
            return {"supported": True, "blocked": False, "target": f"{host}:{port}",
                    "detail": "a packet left the host: no OS-level egress filter applies to this process"}
        return {"supported": True, "blocked": False, "target": f"{host}:{port}",
                "detail": f"connect() failed with {errno.errorcode.get(err, err)}, not a policy refusal"}
    finally:
        libc.close(fd)


