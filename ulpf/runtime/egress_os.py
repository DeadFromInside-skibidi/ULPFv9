EBPF_SOURCE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ebpf", "ulpf_egress.bpf.c")


def _lpm_key(net) -> str:
    """bpftool hex of struct lpm4/lpm6: prefixlen (u32, host little-endian) + address (network order)."""
    return " ".join(f"{b:02x}" for b in net.prefixlen.to_bytes(4, "little") + net.network_address.packed)


def render_ebpf(allow: list[str], cgroup: str = "/sys/fs/cgroup/system.slice/ulpf.service",
                pin: str = "/sys/fs/bpf/ulpf_egress", allow_dns: bool = False) -> str:
    """Shell script: compile + load the cgroup/connect{4,6} and sendmsg{4,6} programs, fill the LPM
    allowlists and attach them to the service cgroup. Blocks native code too (Rust, C, librdkafka)."""
    entries = list(allow or []) + (resolv_conf_nameservers() if allow_dns else [])
    v4, v6, unresolved = resolve_allow(entries)
    lines = ["#!/bin/sh"] + _header(unresolved, "ebpf") + [
        "# Requires: Linux >= 5.8 with cgroup v2, clang, bpftool, libbpf headers; run as root.",
        "set -eu",
        f'SRC="${{ULPF_EBPF_SRC:-{EBPF_SOURCE}}}"',
        f'CG="{cgroup}"',
        f'PIN="{pin}"',
        'OBJ="$(mktemp -d)/ulpf_egress.bpf.o"',
        'ARCH="$(uname -m | sed -e s/x86_64/x86/ -e s/aarch64/arm64/)"',
        'clang -O2 -g -target bpf -D__TARGET_ARCH_"$ARCH" -I/usr/include/"$(uname -m)"-linux-gnu -c "$SRC" -o "$OBJ"',
        'for t in connect4 connect6 sendmsg4 sendmsg6; do bpftool cgroup detach "$CG" "$t" pinned "$PIN/ulpf_$t" '
        '2>/dev/null || true; done',
        'rm -rf "$PIN" && mkdir -p "$PIN/maps"',
        'bpftool prog loadall "$OBJ" "$PIN" pinmaps "$PIN/maps"',
    ]
    for n in v4:
        lines.append(f'bpftool map update pinned "$PIN/maps/allow4" key hex {_lpm_key(ipaddress.ip_network(n))} '
                     'value hex 01')
    for n in v6:
        lines.append(f'bpftool map update pinned "$PIN/maps/allow6" key hex {_lpm_key(ipaddress.ip_network(n))} '
                     'value hex 01')
    lines += ['for t in connect4 connect6 sendmsg4 sendmsg6; do',
              '  bpftool cgroup attach "$CG" "$t" pinned "$PIN/ulpf_$t" multi',
              'done',
              'echo "ULPF eBPF egress policy attached to $CG"',
              'bpftool cgroup show "$CG"']
    return "\n".join(lines) + "\n"


def complement(nets: list[str], version: int) -> list[str]:
    """Address ranges ('a-b') covering everything outside ``nets`` (one IP family)."""
    full = ipaddress.ip_network("0.0.0.0/0" if version == 4 else "::/0")
    keep = sorted((ipaddress.ip_network(n) for n in nets if ipaddress.ip_network(n).version == version),
                  key=lambda n: int(n.network_address))
    out, cur = [], int(full.network_address)
    last = int(full.broadcast_address)
    cls = ipaddress.IPv4Address if version == 4 else ipaddress.IPv6Address
    for n in keep:
        lo, hi = int(n.network_address), int(n.broadcast_address)
        if lo > cur:
            out.append(f"{cls(cur)}-{cls(lo - 1)}")
        cur = max(cur, hi + 1)
    if cur <= last:
        out.append(f"{cls(cur)}-{cls(last)}")
    return out


def render_wfp(allow: list[str], program: str | None = None, service: str | None = None,
               allow_dns: bool = False, group: str = "ULPF Egress") -> str:
    """PowerShell: Windows Defender Firewall (WFP) outbound block rules for the ULPF executable
    covering every address outside the allowlist. Windows evaluates Block before Allow, so the
    allowlist is enforced as the complement of the allowed networks. Run elevated."""
    entries = list(allow or []) + (resolv_conf_nameservers() if allow_dns else [])
    v4, v6, unresolved = resolve_allow(entries)
    v4 = ["127.0.0.0/8"] + [n for n in v4 if n != "127.0.0.0/8"]
    v6 = ["::1/128"] + [n for n in v6 if n != "::1/128"]
    prog = program or sys.executable

    def ps_list(items):
        return "@(" + ", ".join(f"'{i}'" for i in items) + ")"
    target = f"-Service '{service}'" if service else f"-Program '{prog}'"
    lines = [f"# {line[2:]}" if line.startswith("# ") else line for line in _header(unresolved, "wfp")] + [
        "#Requires -RunAsAdministrator",
        '$ErrorActionPreference = "Stop"',
        f'Get-NetFirewallRule -Group "{group}" -ErrorAction SilentlyContinue | Remove-NetFirewallRule',
    ]
    for fam, ranges in (("IPv4", complement(v4, 4)), ("IPv6", complement(v6, 6))):
        if ranges:
            lines.append(f'New-NetFirewallRule -DisplayName "ULPF egress: block non-allowlisted {fam}" '
                         f'-Group "{group}" -Direction Outbound -Action Block {target} -Profile Any '
                         f'-RemoteAddress {ps_list(ranges)} -Enabled True | Out-Null')
    lines += [f'Get-NetFirewallRule -Group "{group}" | Format-Table DisplayName, Enabled, Action, Direction',
              'Write-Host "ULPF WFP egress policy applied. Verify: ulpf airgap os-check"']
    return "\r\n".join(lines) + "\r\n"
